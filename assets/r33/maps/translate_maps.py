# Build sorted TR keys by length (desc) for exact replacement
TR_KEYS = sorted(TR.keys(), key=len, reverse=True)
MORPH_KEYS = sorted(MORPH.keys(), key=len, reverse=True)

def morph_replace(t):
    changed = True
    while changed:
        changed = False
        # exact dictionary hits first (so sub-parts like 麥克米蘭莊園 translate)
        for k in TR_KEYS:
            if k in t:
                t = t.replace(k, TR[k])
                changed = True
        for m in MORPH_KEYS:
            if m in t:
                t = t.replace(m, MORPH[m])
                changed = True
    # collapse multiple spaces, trim
    t = re.sub(r'\s+', ' ', t).strip()
    return t

def translate_value(v):
    v = v.strip()
    if v in TR:
        return TR[v]
    # trailing parenthetical code, e.g. 外圍林地（outer_woods）
    mm = re.match(r'^(.*)（([^）]+)）$', v)
    if mm:
        body, code = mm.group(1), mm.group(2)
        tb = TR.get(body, morph_replace(body))
        return tb + " (" + code + ")"
    # fallback: morpheme decomposition
    return morph_replace(v)

def convert_parens(s):
    return s.replace('（', '(').replace('）', ')')

