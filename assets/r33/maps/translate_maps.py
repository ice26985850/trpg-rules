# ---------------------------------------------------------------------------
def main():
    yaml_files = sorted(glob.glob(os.path.join(SRC, "*.yaml")))
    svg_files = sorted(glob.glob(os.path.join(SRC, "*.svg")))
    for f in yaml_files + svg_files:
        base = os.path.basename(f)
        with open(f, encoding='utf-8') as fh:
            text = fh.read()
        if f.endswith('.yaml'):
            out = translate_yaml(text)
        else:
            out = translate_svg(text)
        dst = os.path.join(DST, base)
        with open(dst, 'w', encoding='utf-8') as fh:
            fh.write(out)
        print("wrote", dst)

if __name__ == '__main__':
    main()
